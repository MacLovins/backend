async def test_config_error_fails_company_and_finishes_run(org_id, fake_worker, fake_parser, monkeypatch):
    service_id, company_id = await seed(org_id)
    run_id = await create_run(org_id, [company_id], [service_id])

    async def broken_bundles(*args, **kwargs):
        raise ValueError("invalid scoring profile")

    monkeypatch.setattr(tasks, "load_bundles", broken_bundles)
    assert await tasks.analyze_company(str(run_id), str(company_id), [str(service_id)]) == "failed"
    run = await run_row(run_id)
    assert (run.status, run.progress["failed"], run.finished_at is not None) == ("failed", 1, True)
    assert "invalid scoring profile" in run.error
    events = await run_events(run_id)
    assert ("company", "failed") in events and events[-1] == ("run", "failed")
    assert fake_worker.calls == []


