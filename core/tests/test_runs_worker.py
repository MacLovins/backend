class RecordingTask:
    def __init__(self) -> None:
        self.kiq_calls: list[tuple] = []
        self.direct_calls: list[tuple] = []

    async def kiq(self, *args) -> None:
        self.kiq_calls.append(args)

    async def __call__(self, *args) -> str:
        self.direct_calls.append(args)
        return "done"


@pytest.mark.parametrize("embedded", [False, True])
async def test_enqueue_goes_to_the_queue_unless_embedded(monkeypatch, embedded: bool) -> None:
    task = RecordingTask()
    monkeypatch.setattr(tasks, "analyze_company", task)
    monkeypatch.setattr(settings, "ENV", "dev")
    monkeypatch.setattr(settings, "EMBEDDED_WORKER", embedded)
    run_id, company_id = uuid4(), uuid4()
    assert await enqueue.enqueue_analysis(run_id, [company_id], [], "full") == 1
    await asyncio.sleep(0)  # let the embedded background task run
    expected = [(str(run_id), str(company_id), [], "full")]
    assert (task.direct_calls, task.kiq_calls) == ((expected, []) if embedded else ([], expected))


