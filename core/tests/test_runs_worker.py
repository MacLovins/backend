# --- item 3: live and replay use the same names and data ------------------------------------------


async def test_live_events_match_the_replay(org_id, fake_worker, fake_parser, client, monkeypatch):
    redis = FakeRedis()
    monkeypatch.setattr(worker_context, "redis", redis)
    service_id, company_id = await seed(org_id)
    run_id = await create_run(org_id, [company_id], [service_id])
    await tasks.analyze_company(str(run_id), str(company_id), [str(service_id)])
    await engine.dispose()

    live = [{"id": m["id"], "event": m["event"], "data": m["data"]} for m in redis.messages]
    assert {m["channel"] for m in redis.messages} == {f"run:{run_id}"}
    replay = parse_sse(client.get(f"/api/v1/runs/{run_id}/events", headers=headers(org_id)).text)
    assert replay == live
    names = [e["event"] for e in live]
    assert set(names) == {"company.stage", "company.done", "run.progress", "run.finished"}
    assert names[-1] == "run.finished" and live[-1]["data"]["status"] == "succeeded"
    stage = next(e for e in live if e["event"] == "company.stage")
    assert {"company_id", "service_id", "stage", "status", "message"} <= set(stage["data"])
    done = next(e for e in live if e["event"] == "company.done")
    assert done["data"]["company_id"] == str(company_id) and done["data"]["scores"]


# --- item 8: outreach is generated by the worker -------------------------------------------------

DRAFT = {
    "channel": "email",
    "subject": "Agentic AI at Acme",
    "body": "Hello, we saw that Acme uses agentic AI for RFQs.",
    "referenced_signals": [],
    "referenced_quotes": [],
    "hook": "agentic AI",
    "call_to_action": "15 minutes next week?",
    "language": "en",
}


async def test_outreach_is_enqueued_and_generated_by_the_worker(org_id, fake_worker, client, monkeypatch):
    service_id, company_id = await seed(org_id)
    await engine.dispose()
    enqueued: list[UUID] = []

    async def fake_enqueue(job_id):
        enqueued.append(job_id)
        return True

    from leadradar_core.modules.outreach import service as outreach_service

    monkeypatch.setattr(outreach_service, "enqueue_outreach", fake_enqueue)
    h = headers(org_id)
    res = client.post(f"/api/v1/leads/{company_id}/outreach", json={"tone": "direct"}, headers=h)
    assert res.status_code == 202, res.text
    job = res.json()
    assert job["status"] == "queued" and job["draft"] is None and job["service_id"] == str(service_id)
    assert enqueued == [UUID(job["id"])]
    assert fake_worker.calls == []  # no LLM inside the request

    llm = FakeLLM([DRAFT])
    monkeypatch.setattr(worker_context, "llm", llm)
    await engine.dispose()  # pooled connections of the TestClient loop
    assert await outreach.generate_outreach(job["id"]) == "succeeded"
    assert llm.calls_for("outreach")
    assert await outreach.generate_outreach(job["id"]) == "skipped"  # a job runs once
    await engine.dispose()

    got = client.get(f"/api/v1/leads/{company_id}/outreach/{job['id']}", headers=h)
    assert got.status_code == 200
    body = got.json()
    assert body["status"] == "succeeded" and body["finished_at"]
    assert body["draft"]["subject"] == DRAFT["subject"] and body["draft"]["body"] == DRAFT["body"]

    assert client.get(f"/api/v1/leads/{company_id}/outreach/{uuid4()}", headers=h).status_code == 404
    assert client.get(f"/api/v1/leads/{uuid4()}/outreach/{job['id']}", headers=h).status_code == 404
    assert client.post(f"/api/v1/leads/{uuid4()}/outreach", json={}, headers=h).status_code == 404
